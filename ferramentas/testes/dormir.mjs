// Dia e noite e dormir na cama (igual ao Quimera, André 2026-11-07). Uso: node ferramentas/testes/dormir.mjs
import { Simulacao, MAPA_CLAREIRA, horaDoJogo, ehNoite, DIA, CAMA, VIGOR, vigorAgora, progressoValido } from '../../shared/index.js';
import './_tudo-aberto.mjs'; // progressão (2026-11-10): este teste não é sobre a névoa nem a trava de nível
const s = new Simulacao(MAPA_CLAREIRA);
const a = s.adicionarJogador('A', 'Ana', undefined, { conta: 1 });
a.criando = false; a.x = -19; a.z = 60; a.prog.ouro = 5000;
const ev = () => { const e = s.eventos; s.eventos = []; return e; };
const avisos = (e) => e.filter((x) => x.t === 'aviso').map((x) => x.texto).join(' | ');
const ok = (c, m) => { if (!c) { console.error('FALHOU', m); process.exitCode = 1; } else console.log('ok', m); };
const agora = Date.now();
ok(Math.abs(horaDoJogo({ h: 8, t: agora }, agora + 30000) - 9) < 1e-6, '1 hora do jogo = 30 s');
ok(ehNoite(19) && ehNoite(2) && !ehNoite(5) && !ehNoite(12), 'noite das 19h às 5h');
s.dormir('A'); ok(avisos(ev()).includes('cama'), 'sem terreno não dorme');
s.comprarLote('A', { x0: -28, z0: 55, x1: -20, z1: 63 }); ev();
a.prog.mochila[10] = { k: 'obra_cama', n: 1 };
s.construir('A', { k: 'cama', x: -25, z: 58.5, r: 0 }); ok(s.loteDe(a).pecas.some((o) => o.k === 'cama'), 'construiu a cama ' + avisos(ev()));
a.x = -23; a.z = 60;
a.prog.dia = { h: 12, t: Date.now() }; s.dormir('A'); ok(avisos(ev()).includes('Só dá para dormir à noite'), 'de dia não dorme');
a.prog.dia = { h: 22, t: Date.now() };
a.vida = 1; a.mana = 0; a.prog.vigor = { v: 10, t: Date.now() };
s.dormir('A'); let e = ev(), d = e.find((x) => x.t === 'dormiu');
ok(d && d.vigor === CAMA.vigor, 'dormiu e ganhou +40 de vigor ' + avisos(e));
ok(Math.abs(horaDoJogo(a.prog.dia) - DIA.acorda) < 0.01, 'acordou às 6h30');
ok(a.vida === a.vidaMax && a.mana === a.manaMax, 'vida e mana cheias');
ok(Math.abs(vigorAgora(a.prog.vigor) - 50) < 0.1, 'vigor 10 -> 50');
a.prog.dia = { h: 23, t: Date.now() };
s.dormir('A'); e = ev(); d = e.find((x) => x.t === 'dormiu');
ok(d && d.vigor === 0 && d.espera > 6 * 3600 - 10, 'dormir de novo antes de 6 h não dá vigor (avisa o tempo)');
a.prog.vigor = { v: 90, t: Date.now() }; a.prog.camaT = Date.now() - CAMA.cada * 1000 - 1; a.prog.dia = { h: 2, t: Date.now() };
s.dormir('A'); d = ev().find((x) => x.t === 'dormiu'); ok(d && d.vigor === 10 && vigorAgora(a.prog.vigor) <= VIGOR.max, 'vigor não passa de 100');
a.x = 0; a.z = 0; a.prog.dia = { h: 22, t: Date.now() }; s.dormir('A'); ok(avisos(ev()).includes('perto da sua cama'), 'longe da cama não dorme');
a.x = -23; a.z = 60; a.combateAte = s.tempo + 5; s.dormir('A'); ok(avisos(ev()).includes('monstros'), 'em combate não dorme');
const q = progressoValido(JSON.parse(JSON.stringify(a.prog)));
ok(q.dia && q.dia.h === 22 && q.camaT > 0, 'relógio e cama ficam salvos na conta');
