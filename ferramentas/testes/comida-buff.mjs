// André 2026-11-24: comida não dá vigor; dá buff (um por vez, morrer tira); subir de nível dá VIGOR.porNivel de vigor
import { Simulacao, MAPA_CLAREIRA, VIGOR, vigorAgora, ITENS, contar, xpProximo, vigorMax, CAMA } from '../../shared/index.js';
import './_tudo-aberto.mjs';
let falhas = 0;
const ok = (c, m) => { console.log((c ? 'ok ' : 'FALHOU ') + m); if (!c) falhas++; };
const s = new Simulacao(MAPA_CLAREIRA);
const a = s.adicionarJogador('A', 'Ana', undefined, { conta: 1 }), p = a.prog; a.criando = false;
const ev = () => { const e = s.eventos; s.eventos = []; return e.filter((x) => x.t === 'aviso').map((x) => x.texto).join(' | '); };
ev();
ok(Object.values(ITENS).every((it) => !it.comida || !it.usar.vigor), 'nenhuma comida dá vigor');
const crit0 = a.st.critico, dano0 = a.st.danoFisico;
p.mochila[3] = { k: 'torta_abobora', n: 2 }; a.vida = a.vidaMax; a.mana = a.manaMax; p.vigor = { v: 50, t: Date.now() };
s.item('A', { acao: 'usar', i: 3 }); let e = ev();
ok(contar(p.mochila, 'torta_abobora') === 1, 'com tudo cheio ainda come o prato que tem buff ' + e);
ok(Math.abs(a.st.critico - crit0 - 0.03) < 1e-6 && a.st.danoFisico > dano0 * 1.04, 'torta: +3% crítico e +5% dano');
ok(Math.abs(vigorAgora(p.vigor) - 50) < 0.1, 'vigor não sobe comendo');
ok(e.includes('Buff') && e.includes('20 min'), 'avisa o buff ' + e);
p.mochila[4] = { k: 'sopa_legumes', n: 1 }; const def0 = a.st.defesa;
s.item('A', { acao: 'usar', i: 4 }); e = ev();
ok(p.buff.k === 'sopa_legumes' && Math.abs(a.st.critico - crit0) < 1e-6 && e.includes('trocado'), 'um buff por vez: a sopa troca a torta ' + e);
ok(a.st.defesa > def0, 'sopa: defesa maior');
p.mochila[5] = { k: 'lambari', n: 1 }; s.item('A', { acao: 'usar', i: 5 }); e = ev();
ok(contar(p.mochila, 'lambari') === 1 && e.includes('satisfeito'), 'peixe cru sem buff com vida cheia não é comido');
p.buff.ate = Date.now() - 1; e = (s.passo(0.05) || []).filter((x) => x.t === 'aviso').map((x) => x.texto).join(' | ');
ok(!p.buff && Math.abs(a.st.defesa - def0) < 1e-6 && e.includes('acabou'), 'o buff acaba no tempo e avisa ' + e);
p.mochila[3] = { k: 'torta_abobora', n: 1 }; s.item('A', { acao: 'usar', i: 3 }); ev();
s.morrer(a); ok(!p.buff && Math.abs(a.st.critico - crit0) < 1e-6, 'morrer tira o buff');
// vigor por nível (André 2026-11-24): o máximo sobe VIGOR.porNivel por nível (sem teto) e enche esse tanto
const s2 = new Simulacao(MAPA_CLAREIRA);
const b = s2.adicionarJogador('B', 'Bia', undefined, { conta: 2 }); b.criando = false;
b.prog.vigor = { v: 20, t: Date.now() }; const nv = b.prog.nivel;
s2.ganharXP(b, xpProximo(nv) + xpProximo(nv + 1));
ok(b.prog.nivel === nv + 2 && Math.abs(vigorAgora(b.prog.vigor) - (20 + 2 * VIGOR.porNivel)) < 0.1, `subiu 2 níveis: +${2 * VIGOR.porNivel} de vigor`);
ok(vigorMax(b.prog) === VIGOR.max + (nv + 1) * VIGOR.porNivel && b.prog.vigor.m === vigorMax(b.prog), 'máximo sobe com o nível: ' + vigorMax(b.prog));
b.prog.vigor = { v: vigorMax(b.prog), t: Date.now() - 999999999, m: vigorMax(b.prog) };
ok(Math.abs(vigorAgora(b.prog.vigor) - vigorMax(b.prog)) < 1e-6 && vigorAgora(b.prog.vigor) > VIGOR.max, 'enche até o máximo novo (passa de 100)');
ok(vigorMax({ nivel: 50 }) === 149, 'Nv 50 = 149 de vigor máximo');
ok(CAMA.vigor === 0, 'cama não dá vigor');
console.log(falhas ? `${falhas} falhas` : 'tudo certo'); process.exit(falhas ? 1 : 0);
